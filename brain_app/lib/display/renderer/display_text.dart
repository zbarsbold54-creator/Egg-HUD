/// 1-bit text rendering for the 128x64 display.
///
/// Uses a compact 5x7 pixel font (classic, readable at small sizes).
/// Supports uppercase, lowercase, digits, and common punctuation.
/// Text is drawn into a [Framebuffer] via [DisplayText.draw].
library;

import '../framebuffer/framebuffer.dart';

class DisplayText {
  /// Draw [text] at (x, y) with the given scale (1 = 5x7, 2 = 10x14).
  static void draw(Framebuffer fb, int x, int y, String text, {int scale = 1, bool on = true}) {
    int cx = x;
    for (int i = 0; i < text.length; i++) {
      final ch = text[i];
      _drawChar(fb, cx, y, ch, scale, on);
      cx += 6 * scale; // 5px glyph + 1px spacing
    }
  }

  /// Measure text width in pixels.
  static int measure(String text, {int scale = 1}) {
    if (text.isEmpty) return 0;
    return text.length * 6 * scale - scale;
  }

  /// Draw text centered horizontally at [y].
  static void drawCentered(Framebuffer fb, int y, String text, {int scale = 1, bool on = true}) {
    final w = measure(text, scale: scale);
    final x = (Framebuffer.width - w) ~/ 2;
    draw(fb, x, y, text, scale: scale, on: on);
  }

  /// Draw wrapped text in a box (x, y, w, h), returns lines drawn.
  static int drawWrapped(Framebuffer fb, int x, int y, int w, int h, String text, {int scale = 1, bool on = true}) {
    final words = text.split(' ');
    final lineH = 8 * scale;
    int cy = y;
    int lines = 0;
    String line = '';
    for (final word in words) {
      final test = line.isEmpty ? word : '$line $word';
      if (measure(test, scale: scale) > w) {
        if (line.isNotEmpty) {
          draw(fb, x, cy, line, scale: scale, on: on);
          cy += lineH;
          lines++;
          if (cy + lineH > y + h) break;
        }
        line = word;
      } else {
        line = test;
      }
    }
    if (line.isNotEmpty && cy + lineH <= y + h) {
      draw(fb, x, cy, line, scale: scale, on: on);
      lines++;
    }
    return lines;
  }

  static void _drawChar(Framebuffer fb, int x, int y, String ch, int scale, bool on) {
    final glyph = _font[ch.toUpperCase()] ?? _font['?']!;
    for (int row = 0; row < 7; row++) {
      final bits = glyph[row];
      for (int col = 0; col < 5; col++) {
        if ((bits >> (4 - col)) & 1 == 1) {
          for (int sy = 0; sy < scale; sy++) {
            for (int sx = 0; sx < scale; sx++) {
              fb.setPixel(x + col * scale + sx, y + row * scale + sy, on);
            }
          }
        }
      }
    }
  }

